@Composable
fun DrywallTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false, // Desactivado por defecto para usar la paleta corporativa
    decimalPrecision: Int = 4,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }
    
    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = android.graphics.Color.TRANSPARENT
            window.navigationBarColor = android.graphics.Color.TRANSPARENT
            
            val insetsController = WindowCompat.getInsetsController(window, view)
            
            // Lógica de iconos de la barra superior:
            // En modo claro (isLight), el Header suele ser Primary (Azul Oscuro) -> Iconos Blancos (false)
            // En modo oscuro (isDark), el Header suele ser Primary (Azul Claro) -> Iconos Negros (true)
            // Para asegurar visibilidad, forzamos iconos blancos si el fondo es oscuro.
            insetsController.isAppearanceLightStatusBars = darkTheme
            insetsController.isAppearanceLightNavigationBars = !darkTheme
        }
    }

    CompositionLocalProvider(LocalDecimalPrecision provides decimalPrecision) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = Shapes,
            content = content
        )
    }
}
